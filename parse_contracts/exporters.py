from __future__ import annotations

import keyword
import re
from typing import Any

from .model import input_schema, response_schema


def safe_name(value: str) -> str:
    name = re.sub(r"[^0-9A-Za-z_]+", "_", value).strip("_").lower() or "endpoint"
    if name[0].isdigit():
        name = "api_" + name
    if keyword.iskeyword(name):
        name += "_"
    return name


def openapi_document(detail: dict[str, Any]) -> dict[str, Any]:
    canonical = detail.get("canonical_scraper_id")
    paths: dict[str, Any] = {}
    for api in detail.get("apis") or []:
        endpoint = str(api.get("endpoint_name"))
        method = str(api.get("method") or "POST").lower()
        path = f"/scraper/{{scraper_id}}/{endpoint}"
        params = [
            {
                "name": "scraper_id",
                "in": "path",
                "required": True,
                "description": "Callable Parse scraper id. The marketplace canonical id is the default.",
                "schema": {"type": "string", "format": "uuid", "default": canonical},
            }
        ]
        in_schema = input_schema(api)
        operation: dict[str, Any] = {
            "operationId": safe_name(endpoint),
            "summary": api.get("description") or endpoint.replace("_", " "),
            "tags": [detail.get("primary_category") or "parse-marketplace"],
            "x-parse-marketplace": {
                "listing_id": detail.get("id"),
                "slug": detail.get("slug"),
                "canonical_scraper_id": canonical,
                "latest_version": detail.get("latest_version"),
                "price_credits": api.get("price"),
                "initiates_session": api.get("initiates_session", False),
            },
            "responses": {
                "200": {
                    "description": "Endpoint result",
                    "content": {"application/json": {"schema": response_schema(api)}},
                },
                "401": {"description": "Missing or invalid X-API-Key"},
            },
            "security": [{"ApiKeyAuth": []}],
        }
        if method == "get":
            for name, schema in (in_schema.get("properties") or {}).items():
                query_schema = {k: v for k, v in schema.items() if k not in {"description", "example"}}
                params.append({"name": name, "in": "query", "required": name in (in_schema.get("required") or []), "description": schema.get("description"), "schema": query_schema})
            operation["parameters"] = params
        else:
            operation["parameters"] = params
            operation["requestBody"] = {"required": bool(in_schema.get("required")), "content": {"application/json": {"schema": in_schema}}}
        paths.setdefault(path, {})[method] = operation
    return {
        "openapi": "3.1.0",
        "info": {
            "title": f"{detail.get('name', 'Parse Marketplace API')} (generated contract)",
            "version": f"1.0.0+parse.{detail.get('latest_version') or 'unversioned'}",
            "description": "Generated from Parse's public no-auth marketplace detail route. It is a compatibility contract for evaluation, not an official Parse export.",
        },
        "servers": [{"url": "https://api.parse.bot"}],
        "paths": paths,
        "components": {"securitySchemes": {"ApiKeyAuth": {"type": "apiKey", "in": "header", "name": "X-API-Key"}}},
    }


def mcp_tools(detail: dict[str, Any]) -> dict[str, Any]:
    prefix = safe_name(str(detail.get("slug") or detail.get("name") or "parse_api"))
    tools = []
    for api in detail.get("apis") or []:
        endpoint = str(api.get("endpoint_name"))
        tools.append({
            "name": f"{prefix}__{safe_name(endpoint)}",
            "description": api.get("description") or endpoint.replace("_", " "),
            "inputSchema": input_schema(api),
            "x-execute": {
                "method": str(api.get("method") or "POST").upper(),
                "url": f"https://api.parse.bot/scraper/{detail.get('canonical_scraper_id')}/{endpoint}",
                "auth_header": "X-API-Key",
            },
        })
    return {"schema": "https://modelcontextprotocol.io/schemas/tools", "generated_from": "parse-marketplace-public-detail", "tools": tools}


def python_type(schema: dict[str, Any]) -> str:
    typ = schema.get("type")
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "array": "list", "object": "dict"}.get(str(typ), "object")


def python_client_source(detail: dict[str, Any]) -> str:
    class_name = "".join(part.title() for part in safe_name(str(detail.get("slug") or "parse_api")).split("_")) + "Client"
    lines = [
        '"""Generated by parse-marketplace-contracts from public Parse Marketplace metadata."""',
        "from __future__ import annotations",
        "",
        "import json",
        "import urllib.parse",
        "import urllib.request",
        "from typing import Any",
        "",
        "",
        f"class {class_name}:",
        "    def __init__(self, api_key: str, base_url: str = 'https://api.parse.bot', scraper_id: str | None = None, timeout: float = 30.0):",
        "        self.api_key = api_key",
        "        self.base_url = base_url.rstrip('/')",
        f"        self.scraper_id = scraper_id or {detail.get('canonical_scraper_id')!r}",
        "        self.timeout = timeout",
        "",
        "    def _request(self, method: str, endpoint: str, values: dict[str, Any]) -> Any:",
        "        url = f'{self.base_url}/scraper/{self.scraper_id}/{endpoint}'",
        "        data = None",
        "        headers = {'X-API-Key': self.api_key, 'Accept': 'application/json'}",
        "        if method == 'GET':",
        "            clean = {k: v for k, v in values.items() if v is not None}",
        "            if clean:",
        "                url += '?' + urllib.parse.urlencode(clean)",
        "        else:",
        "            data = json.dumps({k: v for k, v in values.items() if v is not None}).encode()",
        "            headers['Content-Type'] = 'application/json'",
        "        request = urllib.request.Request(url, data=data, headers=headers, method=method)",
        "        with urllib.request.urlopen(request, timeout=self.timeout) as response:",
        "            return json.loads(response.read().decode())",
    ]
    for api in detail.get("apis") or []:
        endpoint = str(api.get("endpoint_name"))
        method = str(api.get("method") or "POST").upper()
        schema = input_schema(api)
        props = schema.get("properties") or {}
        required = set(schema.get("required") or [])
        ordered = sorted(props, key=lambda n: (n not in required, n))
        args = []
        for name in ordered:
            typ = python_type(props[name])
            if name in required:
                args.append(f"{safe_name(name)}: {typ}")
            else:
                args.append(f"{safe_name(name)}: {typ} | None = None")
        signature = ", ".join(["self"] + args)
        doc = str(api.get("description") or endpoint.replace("_", " ")).replace('"""', "'''")
        mapping = ", ".join(f"{name!r}: {safe_name(name)}" for name in ordered)
        lines.extend(["", f"    def {safe_name(endpoint)}({signature}) -> Any:", f"        \"\"\"{doc}\"\"\"", f"        return self._request({method!r}, {endpoint!r}, {{{mapping}}})"])
    lines.append("")
    return "\n".join(lines)
